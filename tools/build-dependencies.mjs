/*
 * Regenerates the dependency data embedded in dependencies.html.
 *
 *   node tools/build-dependencies.mjs
 *
 * Reads every published Tharga.* package from nuget.org, pulls the latest
 * .nuspec for each, and rewrites the PKGS block between the PKGS:start /
 * PKGS:end markers. Nothing else in the page is touched apart from the
 * "read from the NuGet manifests on <date>" line in the footer.
 *
 * Only structure is written out: the dependency edges and the count of
 * non-Tharga dependencies. Versions and download counts change constantly and
 * are fetched live by the page itself, so they are deliberately NOT baked in.
 *
 * Note: the NuGet search API does not return unlisted packages, so anything
 * unlisted (currently Tharga.Logging) is invisible here by design.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGE = join(ROOT, "dependencies.html");

/* Published under the Thargelion owner but not part of the public component
   set — no public repo, and no internal dependencies either way. */
const EXCLUDE = new Set(["Tharga.Neurolito.Client"]);

const SEARCH = "https://azuresearch-usnc.nuget.org/query?q=Tharga&take=200&prerelease=true&semVerLevel=2.0.0";

async function main() {
	const res = await fetch(SEARCH);
	if (!res.ok) throw new Error(`search failed: ${res.status}`);
	const { data } = await res.json();

	const found = data
		.filter((p) => p.id.toLowerCase().startsWith("tharga") && !EXCLUDE.has(p.id))
		.map((p) => ({ id: p.id, version: p.version }))
		.sort((a, b) => a.id.localeCompare(b.id));

	if (!found.length) throw new Error("no packages returned — refusing to write an empty page");

	const known = new Set(found.map((p) => p.id));
	const pkgs = {};

	for (const p of found) {
		const low = p.id.toLowerCase();
		const url = `https://api.nuget.org/v3-flatcontainer/${low}/${p.version.toLowerCase()}/${low}.nuspec`;
		const r = await fetch(url);
		if (!r.ok) throw new Error(`nuspec ${p.id}@${p.version} -> ${r.status}`);
		const xml = await r.text();

		// dependency ids, union across every target framework group
		const ids = new Set([...xml.matchAll(/<dependency\s+id="([^"]+)"/g)].map((m) => m[1]));
		const internal = [...ids].filter((d) => known.has(d)).sort();
		const external = [...ids].filter((d) => !d.toLowerCase().startsWith("tharga"));

		pkgs[p.id] = { x: external.length, dep: internal };
		console.log(`${p.id}@${p.version} — ${internal.length} internal, ${external.length} external`);
	}

	const body = Object.keys(pkgs)
		.map((id) => `\t\t\t\t${JSON.stringify(id)}:${JSON.stringify(pkgs[id])}`)
		.join(",\n");

	const block =
		"/* PKGS:start — generated by tools/build-dependencies.mjs, do not edit by hand */\n" +
		"\t\t\tvar PKGS = {\n" + body + "\n\t\t\t};\n" +
		"\t\t\t/* PKGS:end */";

	let html = readFileSync(PAGE, "utf8");
	const marker = /\/\* PKGS:start[\s\S]*?\/\* PKGS:end \*\//;
	if (!marker.test(html)) throw new Error("PKGS markers not found in dependencies.html");

	const today = new Date().toISOString().slice(0, 10);
	html = html.replace(marker, block).replace(/manifests on \d{4}-\d{2}-\d{2}/, `manifests on ${today}`);

	writeFileSync(PAGE, html);

	const edges = Object.values(pkgs).reduce((s, p) => s + p.dep.length, 0);
	console.log(`\nwrote ${found.length} packages, ${edges} internal links to dependencies.html (${today})`);
}

main().catch((err) => {
	console.error(err.message);
	process.exit(1);
});
